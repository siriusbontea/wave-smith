/**
 * lib/grok/plan.ts — turn an xAI chat completion into lyrics plus a song plan.
 *
 * Wavesmith adds no content filter of its own. If the hosted model refuses,
 * callers fall back to the local writer. Unrestricted mode never reaches this
 * module (see lib/grok/mode.ts).
 */
import { z } from "zod";
import { describeVocalLanguage } from "@/lib/lyrics/language";
import type { LyricsBrief } from "@/lib/lyrics/types";

export interface SongPlan {
  lyrics: string;
  sections: string[];
  bpm: number | null;
  keyScale: string | null;
  timeSignature: "2" | "3" | "4" | "6" | null;
  styleTags: string[];
  structure: string;
}

export class GrokRefusalError extends Error {
  constructor(message = "Grok declined the lyric request") {
    super(message);
    this.name = "GrokRefusalError";
  }
}

export class GrokUnconfiguredError extends Error {
  constructor() {
    super("Grok API key is not set");
    this.name = "GrokUnconfiguredError";
  }
}

const PlanSchema = z.object({
  lyrics: z.string().min(1),
  sections: z.array(z.string()).optional(),
  bpm: z.number().nullable().optional(),
  keyScale: z.string().nullable().optional(),
  timeSignature: z.string().nullable().optional(),
  styleTags: z.array(z.string()).optional(),
  structure: z.string().optional(),
});

const SECTION_TAG = /\[(verse|chorus|bridge|intro|outro|pre-chorus|hook|break)/i;
const REFUSAL =
  /\b(i (?:can(?:not|'t)|won'?t|must refuse|am unable|cannot)|against (?:my|the) (?:guidelines|policies)|i'm unable|not able to (?:write|create|help))\b/i;

export function buildGrokMessages(brief: LyricsBrief): Array<{ role: "system" | "user"; content: string }> {
  const language = describeVocalLanguage(brief.language);
  const system = `You are a professional songwriter helping plan a track that will be generated by a local music model.

Return ONLY a JSON object with these keys:
- lyrics: song lyrics using section tags on their own lines, exactly like [verse], [chorus], [bridge], [intro], [outro]
- sections: array of those section names in order
- bpm: integer tempo or null
- keyScale: a key such as "A minor" or null
- timeSignature: one of "2", "3", "4", "6", or null
- styleTags: short genre/mood tags
- structure: a one-line form such as "verse-chorus-verse-chorus-bridge-chorus"

Write every sung line in ${language}.
No commentary, no markdown fences, no content warnings.
When the user asks for explicit language, write it plainly.`;

  const parts = [`The song is about: ${brief.prompt}`];
  if (brief.tags?.length) parts.push(`Style to honor: ${brief.tags.join(", ")}`);
  if (brief.structureHints) parts.push(`Structure hint: ${brief.structureHints}`);
  if (brief.language) parts.push(`Language code: ${brief.language}`);
  if (brief.explicit) {
    parts.push("Explicit content is requested. Write it plainly and naturally where it serves the song.");
  }
  return [
    { role: "system", content: system },
    { role: "user", content: parts.join("\n") },
  ];
}

function stripFences(raw: string): string {
  const trimmed = raw.trim();
  const fenced = /^```(?:json)?\s*([\s\S]*?)\s*```$/i.exec(trimmed);
  return (fenced?.[1] ?? trimmed).trim();
}

function clampBpm(n: number | null | undefined): number | null {
  if (n == null || !Number.isFinite(n)) return null;
  const rounded = Math.round(n);
  if (rounded < 30 || rounded > 300) return null;
  return rounded;
}

function normalizeTime(raw: string | null | undefined): SongPlan["timeSignature"] {
  if (!raw) return null;
  const hit = /[2346]/.exec(raw);
  if (!hit) return null;
  return hit[0] as SongPlan["timeSignature"];
}

function sectionsFromLyrics(lyrics: string): string[] {
  const found: string[] = [];
  for (const line of lyrics.split("\n")) {
    const m = /^\s*\[([^\]]+)\]\s*$/.exec(line);
    if (m?.[1]) found.push(m[1].toLowerCase());
  }
  return found;
}

export function parseGrokPlan(raw: string): SongPlan {
  const text = stripFences(raw);
  if (!text) throw new Error("Grok returned an empty reply");

  let lyrics = "";
  let bpm: number | null = null;
  let keyScale: string | null = null;
  let timeSignature: SongPlan["timeSignature"] = null;
  let styleTags: string[] = [];
  let structure = "";
  let sections: string[] = [];

  try {
    const parsed = PlanSchema.safeParse(JSON.parse(text));
    if (parsed.success) {
      lyrics = parsed.data.lyrics.trim();
      bpm = clampBpm(parsed.data.bpm);
      const key = parsed.data.keyScale?.trim();
      keyScale = key ? key.slice(0, 20) : null;
      timeSignature = normalizeTime(parsed.data.timeSignature);
      styleTags = (parsed.data.styleTags ?? [])
        .map((t) => t.trim().slice(0, 40))
        .filter(Boolean)
        .slice(0, 8);
      structure = (parsed.data.structure ?? "").trim().slice(0, 200);
      sections = (parsed.data.sections ?? []).map((s) => s.trim().toLowerCase()).filter(Boolean).slice(0, 12);
    }
  } catch {
    lyrics = "";
  }

  if (!lyrics && SECTION_TAG.test(text) && !REFUSAL.test(text)) {
    lyrics = text;
  }

  if (!SECTION_TAG.test(lyrics)) {
    if (REFUSAL.test(text) || REFUSAL.test(lyrics)) throw new GrokRefusalError();
    throw new Error("Grok didn't return structured lyrics");
  }

  if (sections.length === 0) sections = sectionsFromLyrics(lyrics);
  return { lyrics, sections, bpm, keyScale, timeSignature, styleTags, structure };
}

export function friendlyGrokError(err: unknown, willFallback: boolean): string {
  const tail = willFallback
    ? " Using the local writer instead."
    : " The local lyrics writer isn't running — write the words yourself, or start Ollama.";
  if (err instanceof GrokRefusalError) {
    return `Grok declined this lyric request.${tail}`;
  }
  if (err instanceof GrokUnconfiguredError) {
    return `Grok hybrid is on, but no API key is set.${tail}`;
  }
  const msg = err instanceof Error ? err.message : "";
  if (/401|403|invalid api key|incorrect api key/i.test(msg)) {
    return `Grok rejected the API key.${tail}`;
  }
  if (/429|rate limit/i.test(msg)) {
    return `Grok is rate-limiting requests.${tail}`;
  }
  if (/offline|network|fetch|timed out|timeout|ECONN|ENOTFOUND|aborted/i.test(msg)) {
    return `Couldn't reach Grok.${tail}`;
  }
  return `Grok didn't answer.${tail}`;
}
